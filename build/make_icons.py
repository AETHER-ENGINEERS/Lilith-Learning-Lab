#!/usr/bin/env python3
"""Generate src/icons.js (Material Design icons, Apache-2.0) from the npm package @material-design-icons/svg.
Usage: npm install @material-design-icons/svg (anywhere), then: python3 make_icons.py <path to node_modules/@material-design-icons/svg>
The generated icons.js is committed, so normal builds do not need npm."""
import json, os, re, sys
NAMES = """school menu_book account_tree science insights library_books settings play_arrow pause skip_previous skip_next chevron_left chevron_right
first_page last_page check close add delete upload_file content_paste share content_copy help_outline volume_up replay lightbulb visibility
arrow_back play_circle quiz route check_circle radio_button_unchecked speed restart_alt terminal code extension flag emoji_events
subtitles format_list_bulleted menu info warning error expand_more auto_stories checklist view_list description edit_note drag_handle
keyboard_return tune history done_all schedule play_lesson text_snippet source download arrow_forward assignment""".split()
src = sys.argv[1]
out = {}
for n in dict.fromkeys(NAMES):
    f = os.path.join(src, "filled", n + ".svg")
    if not os.path.exists(f):
        print("missing", n); continue
    t = open(f).read()
    out[n] = re.search(r'<svg[^>]*>(.*)</svg>', t, re.S).group(1)
js = "/* Material Design icons (Apache License 2.0, https://github.com/google/material-design-icons). Generated by make_icons.py */\n(function(root){root.LilithIcons=" + json.dumps(out, separators=(",", ":")) + ";})(typeof window!=='undefined'?window:globalThis);\n"
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "icons.js"), "w").write(js)
print(len(out), "icons,", len(js), "bytes")
